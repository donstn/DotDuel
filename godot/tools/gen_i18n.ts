// Every message of the app, flattened to dotted keys ("howto.scenes.claim.title").
// Functions become templates with {0}, {1}… One-number functions (counts) are
// exported as three plural forms [one, few, many] sampled per language — the
// order Lang._form() picks from.
const SAMPLE: Record<string, number[]> = { lt: [1, 2, 10] };
const SENT = (i: number) => `\u0001${i}\u0001`;
function flatten(m: unknown, code: string, prefix = '', acc: Record<string, string | string[]> = {}) {
  if (typeof m === 'string') acc[prefix] = m;
  else if (typeof m === 'function') {
    const f = m as (...a: unknown[]) => string;
    try {
      if (f.length === 1) {
        const forms = (SAMPLE[code] ?? [1, 2, 5]).map((n) =>
          String(f(n)).replace(new RegExp(`(?<![0-9])${n}(?![0-9])`), '{0}'),
        );
        acc[prefix] = forms.every((x) => x === forms[0]) ? forms[0] : forms;
      } else {
        const args = Array.from({ length: f.length }, (_, i) => SENT(i));
        acc[prefix] = String(f(...args)).replace(/\u0001(\d+)\u0001/g, '{$1}');
      }
    } catch {
      /* needs real objects: handled by hand in strings.gd */
    }
  } else if (Array.isArray(m)) m.forEach((v, i) => flatten(v, code, `${prefix}.${i}`, acc));
  else if (m && typeof m === 'object')
    for (const [k, v] of Object.entries(m)) flatten(v, code, prefix ? `${prefix}.${k}` : k, acc);
  return acc;
}
